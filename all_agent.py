def review_guardrail(result: TaskOutput) -> tuple[bool, object]:
    """Валидатор формата вердикта: не прошёл → задача переделывается."""
    text = result.raw or ""
    if "VERDICT:" not in text:
        return (False, "Нет строки 'VERDICT: PASS/FAIL'. Верни отчёт строго в заданном формате.")
    return (True, result)

